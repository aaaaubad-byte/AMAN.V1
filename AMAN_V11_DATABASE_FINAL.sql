create or replace function public.create_customer_profile(
  p_name text,
  p_email text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  aa public.auth_account;
  cp public.customer_profile;
  pb public.points_balance;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;

  insert into public.auth_account(auth_user_id)
  values(auth.uid())
  on conflict(auth_user_id) do update set updated_at=now()
  returning * into aa;

  insert into public.customer_profile(
    auth_account_id,public_user_code,name,email
  )
  values(
    aa.id,public.generate_public_code('U'),trim(p_name),p_email
  )
  on conflict(auth_account_id)
  do update set name=excluded.name,email=excluded.email,updated_at=now()
  returning * into cp;

  insert into public.points_balance(customer_id)
  values(cp.id)
  on conflict(customer_id) do nothing
  returning * into pb;

  return jsonb_build_object(
    'customer_id',cp.id,
    'public_user_code',cp.public_user_code,
    'account_type',cp.account_type,
    'account_status',cp.account_status
  );
end;
$$;

