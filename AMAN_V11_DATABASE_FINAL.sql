create or replace function public.mark_notification_read(
  p_notification_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer_id uuid;
begin
  select cp.id into v_customer_id
  from public.customer_profile cp
  join public.auth_account aa on aa.id=cp.auth_account_id
  where aa.auth_user_id=auth.uid();

  if v_customer_id is null then raise exception 'CUSTOMER_NOT_FOUND'; end if;

  update public.customer_notification
