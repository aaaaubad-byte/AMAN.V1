create or replace function public.submit_points_purchase(
  p_package_id uuid,
  p_payment_method_id uuid,
  p_transfer_reference text,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_aa uuid;
  v_customer_id uuid;
  v_package public.points_package;
  v_method public.payment_method;
  v_purchase public.points_purchase;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if nullif(trim(p_idempotency_key),'') is null then raise exception 'IDEMPOTENCY_KEY_REQUIRED'; end if;
  if nullif(trim(p_transfer_reference),'') is null then raise exception 'PAYMENT_REFERENCE_REQUIRED'; end if;

  select id into v_aa from public.auth_account where auth_user_id=auth.uid();
  select id into v_customer_id from public.customer_profile
  where auth_account_id=v_aa and account_status='ACTIVE';

  if v_customer_id is null then raise exception 'CUSTOMER_NOT_FOUND'; end if;

  select * into v_package
  from public.points_package
  where id=p_package_id and is_active=true and is_visible=true;

  if v_package.id is null then raise exception 'PACKAGE_NOT_AVAILABLE'; end if;

  select * into v_method
  from public.payment_method
  where id=p_payment_method_id and is_active=true and is_visible=true;

  if v_method.id is null then raise exception 'PAYMENT_METHOD_NOT_AVAILABLE'; end if;

  if exists(
    select 1 from public.points_purchase
    where customer_id=v_customer_id
      and transfer_reference=trim(p_transfer_reference)
      and status in ('PENDING','APPROVED')
  ) then
    raise exception 'PAYMENT_REFERENCE_ALREADY_USED';
  end if;

  insert into public.points_purchase(
    public_purchase_code,customer_id,package_id,payment_method_id,
    package_name_snapshot,points_snapshot,price_snapshot,currency_snapshot,
    payment_method_name_snapshot,receiving_account_snapshot,
    payment_instructions_snapshot,transfer_reference
  )
  values(
    public.generate_public_code('P'),
    v_customer_id,v_package.id,v_method.id,
    v_package.name,v_package.points,v_package.price,v_package.currency,
    v_method.name,v_method.receiving_account,v_method.transfer_instructions,
    trim(p_transfer_reference)
  )
  returning * into v_purchase;

  insert into public.operation(
    operation_key,operation_type,actor_type,actor_id,
    entity_type,entity_id,status,idempotency_key,completed_at
  )
  values(
    public.generate_public_code('OP'),'PURCHASE_POINTS','CUSTOMER',v_customer_id,
    'points_purchase',v_purchase.id,'COMPLETED',p_idempotency_key,now()
  );

  return jsonb_build_object(
    'purchase_id',v_purchase.id,
    'purchase_code',v_purchase.public_purchase_code,
    'status',v_purchase.status
  );
end;
$$;

