-- ================================================================

create or replace function public.approve_points_purchase(
  p_purchase_id uuid,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_purchase public.points_purchase;
  v_balance public.points_balance;
  v_subscriber public.subscriber_identity;
  v_customer public.customer_profile;
  v_admin uuid;
  v_operation uuid;
begin
  if not public.has_admin_permission('points_purchases.approve') then
    raise exception 'FORBIDDEN';
  end if;

  if nullif(trim(p_idempotency_key),'') is null then
    raise exception 'IDEMPOTENCY_KEY_REQUIRED';
  end if;

  select * into v_purchase
  from public.points_purchase
  where id=p_purchase_id
  for update;

  if v_purchase.id is null then raise exception 'PURCHASE_NOT_FOUND'; end if;
  if v_purchase.status <> 'PENDING' then raise exception 'PURCHASE_NOT_PENDING'; end if;

  select * into v_customer
  from public.customer_profile
  where id=v_purchase.customer_id
  for update;

  insert into public.points_balance(customer_id)
  values(v_customer.id)
  on conflict(customer_id) do nothing;

  select * into v_balance
  from public.points_balance
  where customer_id=v_customer.id
  for update;

  update public.points_purchase
  set status='APPROVED',
      reviewed_at=now(),
      reviewed_by=public.current_admin_id(),
      updated_at=now()
  where id=v_purchase.id
  returning * into v_purchase;

  if not exists(
    select 1 from public.subscriber_identity
    where customer_profile_id=v_customer.id
  ) then
    insert into public.subscriber_identity(
      customer_profile_id,public_subscriber_code
    )
    values(v_customer.id,public.generate_public_code('S'))
    returning * into v_subscriber;
  else
    select * into v_subscriber
    from public.subscriber_identity
    where customer_profile_id=v_customer.id;
  end if;

  update public.customer_profile
  set account_type='SUBSCRIBER',updated_at=now()
  where id=v_customer.id;

  insert into public.points_ledger(
    customer_id,direction,amount,balance_before,balance_after,
    entry_type,source_type,source_id,description,created_by
  )
  values(
    v_customer.id,'CREDIT',v_purchase.points_snapshot,
    v_balance.balance,v_balance.balance+v_purchase.points_snapshot,
    'PURCHASE_CREDIT','points_purchase',v_purchase.id,
    'Approved points purchase',public.current_admin_id()
  );

  update public.points_balance
  set balance=balance+v_purchase.points_snapshot,updated_at=now()
  where id=v_balance.id;

  insert into public.financial_ledger(
    entry_type,direction,amount,currency,source_type,source_id,
    description,created_by
  )
  values(
    'POINTS_SALE','INFLOW',v_purchase.price_snapshot,v_purchase.currency_snapshot,
    'points_purchase',v_purchase.id,'Approved points purchase',public.current_admin_id()
  );

  insert into public.financial_account(currency,balance)
  values(v_purchase.currency_snapshot,v_purchase.price_snapshot)
  on conflict(currency)
  do update set balance=public.financial_account.balance+excluded.balance,
                updated_at=now();

  insert into public.operation(
    operation_key,operation_type,actor_type,actor_id,
    entity_type,entity_id,status,idempotency_key,completed_at
  )
  values(
    public.generate_public_code('OP'),'APPROVE_PURCHASE','ADMIN',
    public.current_admin_id(),'points_purchase',v_purchase.id,
    'COMPLETED',p_idempotency_key,now()
  )
  returning id into v_operation;

  insert into public.notification_event(event_type,source_type,source_id)
  values('POINTS_PURCHASE_APPROVED','points_purchase',v_purchase.id);

  insert into public.audit_log(
    actor_type,actor_id,operation_id,entity_type,entity_id,action,
    permission_code,after_state
  )
  values(
    'ADMIN',public.current_admin_id(),v_operation,
    'points_purchase',v_purchase.id,'APPROVE_PURCHASE',
    'points_purchases.approve',to_jsonb(v_purchase)
  );

  return jsonb_build_object(
    'purchase_id',v_purchase.id,
    'status',v_purchase.status,
    'subscriber_id',v_subscriber.id,
    'balance',v_balance.balance+v_purchase.points_snapshot
  );
end;
$$;

