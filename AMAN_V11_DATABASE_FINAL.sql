create or replace function public.add_customer_number(
  p_phone text,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_auth_account_id uuid;
  v_customer_id uuid;
  v_phone text;
  v_company_id uuid;
  v_phone_id uuid;
  v_cn public.customer_number;
begin
  v_auth_account_id := public.ensure_auth_account();

  select id into v_customer_id
  from public.customer_profile
  where auth_account_id=v_auth_account_id
    and account_status='ACTIVE'
  for update;

  if v_customer_id is null then raise exception 'CUSTOMER_NOT_FOUND'; end if;

  if nullif(trim(p_idempotency_key),'') is null then
    raise exception 'IDEMPOTENCY_KEY_REQUIRED';
  end if;

  v_phone := public.normalize_phone(p_phone);

  if length(v_phone) < 7 then raise exception 'INVALID_PHONE'; end if;

  select telecom_company_id into v_company_id
  from public.telecom_prefix
  where status='ACTIVE'
    and v_phone like prefix || '%'
  order by length(prefix) desc
  limit 1;

  if v_company_id is null then raise exception 'TELECOM_COMPANY_NOT_DETECTED'; end if;

  insert into public.phone_number(
    normalized_phone,display_phone,telecom_company_id
  )
  values(v_phone,p_phone,v_company_id)
  on conflict(normalized_phone)
  do update set display_phone=excluded.display_phone,
                telecom_company_id=excluded.telecom_company_id,
                updated_at=now()
  returning id into v_phone_id;

  insert into public.customer_number(
    customer_id,phone_number_id,public_added_number_code,status
  )
  values(
    v_customer_id,v_phone_id,public.generate_public_code('N'),'ACTIVE'
  )
  on conflict(customer_id,phone_number_id)
  do update set status='ACTIVE',updated_at=now()
  returning * into v_cn;

  insert into public.operation(
    operation_key,operation_type,actor_type,actor_id,
    entity_type,entity_id,status,idempotency_key,completed_at
  )
  values(
    public.generate_public_code('OP'),'ADD_NUMBER','CUSTOMER',v_customer_id,
    'customer_number',v_cn.id,'COMPLETED',p_idempotency_key,now()
  );

  return jsonb_build_object(
    'customer_number_id',v_cn.id,
    'phone_number_id',v_phone_id,
    'status',v_cn.status
  );
end;
$$;

