create or replace function public.admin_grant_points(
  p_customer_id uuid,
  p_amount bigint,
  p_reason text,
  p_idempotency_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_balance public.points_balance;
  v_operation uuid;
begin
  if not public.has_admin_permission('finance.write') then
    raise exception 'FORBIDDEN';
  end if;

  if p_amount <= 0 then raise exception 'INVALID_AMOUNT'; end if;
  if nullif(trim(p_reason),'') is null then raise exception 'REASON_REQUIRED'; end if;

  insert into public.points_balance(customer_id)
  values(p_customer_id)
  on conflict(customer_id) do nothing;

  select * into v_balance
  from public.points_balance
  where customer_id=p_customer_id
  for update;

  insert into public.points_ledger(
    customer_id,direction,amount,balance_before,balance_after,
    entry_type,source_type,description,created_by
  )
  values(
    p_customer_id,'CREDIT',p_amount,v_balance.balance,
    v_balance.balance+p_amount,'ADMIN_GRANT','admin_grant',
    p_reason,public.current_admin_id()
  );

  update public.points_balance
  set balance=balance+p_amount,updated_at=now()
  where id=v_balance.id;

  insert into public.operation(
    operation_key,operation_type,actor_type,actor_id,
    entity_type,entity_id,status,idempotency_key,completed_at
  )
  values(
    public.generate_public_code('OP'),'ADMIN_GRANT','ADMIN',
    public.current_admin_id(),'customer_profile',p_customer_id,
    'COMPLETED',p_idempotency_key,now()
  )
  returning id into v_operation;

  insert into public.audit_log(
    actor_type,actor_id,operation_id,entity_type,entity_id,action,
    permission_code,reason
  )
  values(
    'ADMIN',public.current_admin_id(),v_operation,
    'customer_profile',p_customer_id,'ADMIN_GRANT',
    'finance.write',p_reason
  );

  return jsonb_build_object(
    'customer_id',p_customer_id,
    'balance',v_balance.balance+p_amount
  );
end;
$$;

