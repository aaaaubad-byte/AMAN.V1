create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.normalize_phone(p_phone text)
returns text
language sql
immutable
as $$
  select regexp_replace(coalesce(p_phone,''), '[^0-9]+', '', 'g');
$$;

create or replace function public.generate_public_code(p_prefix text)
returns text
language plpgsql
as $$
begin
  return upper(coalesce(p_prefix,'X')) || '-' ||
         to_char(clock_timestamp(),'YYMMDDHH24MISSMS') || '-' ||
         upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));
end;
$$;

create or replace function public.current_admin_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select ai.id
  from public.admin_identity ai
  join public.auth_account aa on aa.id = ai.auth_account_id
  where aa.auth_user_id = auth.uid()
    and ai.status = 'ACTIVE';
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(
    select 1 from public.admin_identity ai
    join public.auth_account aa on aa.id = ai.auth_account_id
    where aa.auth_user_id = auth.uid()
      and ai.status = 'ACTIVE'
  );
$$;

create or replace function public.has_admin_permission(p_permission text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(
    select 1
    from public.admin_identity ai
    join public.auth_account aa on aa.id = ai.auth_account_id
    join public.admin_assignments ass on ass.admin_id = ai.id and ass.status = 'ACTIVE'
    join public.role_permissions rp on rp.role_id = ass.role_id
    join public.permissions p on p.id = rp.permission_id and p.status = 'ACTIVE'
    where aa.auth_user_id = auth.uid()
      and ai.status = 'ACTIVE'
      and p.code = p_permission
  );
$$;

